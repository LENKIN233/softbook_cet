#!/usr/bin/env node
// Consume immutable card-make handoffs; do not author or approve content here.
import {createHash} from 'node:crypto';
import {copyFileSync, mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, resolve, join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {normalizeFullTrackCandidate} from './run_audio_bundle_candidate_mobile_acceptance.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const input = process.argv[2];
const upstreamCommit = process.argv[3];
if (!input || !/^[a-f0-9]{40}$/.test(upstreamCommit ?? '')) {
  throw new Error('Usage: install_bundled_card_library.mjs <handoff-directory> <card-make-commit>');
}
const contentRoot = join(root, 'infra/cloudbase/functions/softbook-api/card-content');
const assetRoot = join(root, 'apps/mobile/assets/card-audio');
const sha256 = bytes => `sha256:${createHash('sha256').update(bytes).digest('hex')}`;
const metadata = {schema_version: 'bundled-card-library.v1', upstream_repository: 'LENKIN233/card-make', upstream_commit: upstreamCommit, release_authorization: 'candidate', tracks: {}};
const sources = {};
// Validate both tracks and every byte before writing any runtime content.
for (const track of ['cet4', 'cet6']) {
  const path = resolve(input, track, `bundled-card-make-v1-${track}-card-source.json`);
  const bytes = readFileSync(path);
  const payload = normalizeFullTrackCandidate(JSON.parse(bytes));
  for (const asset of payload.assets) {
    const file = readFileSync(resolve(dirname(path), asset.asset_path));
    if (file.length !== asset.size_bytes || sha256(file) !== asset.sha256) throw new Error(`Corrupt audio: ${asset.asset_id}`);
  }
  sources[track] = {path, payload};
  metadata.tracks[track] = {payload_sha256: sha256(bytes), content_version: payload.content_version, card_count: payload.card_records.length, box_count: new Set(payload.card_records.map(card => card.knowledge_ref)).size, audio_asset_count: payload.assets.length};
}
mkdirSync(contentRoot, {recursive: true});
const imports = [];
const trackEntries = [];
const clientImports = [];
const clientTracks = [];
const clientRoot = '../../../../infra/cloudbase/functions/softbook-api/card-content/';
for (const [track, {path, payload}] of Object.entries(sources)) {
  const chunks = [];
  const clientChunks = [];
  for (let offset = 0; offset < payload.card_records.length; offset += 200) {
    const name = `${track}-${offset / 200}`;
    writeFileSync(join(contentRoot, `${name}.json`), `${JSON.stringify(payload.card_records.slice(offset, offset + 200), null, 2)}\n`);
    chunks.push(`...require('./${name}.json')`);
    const identifier = name.replace('-', '_');
    clientImports.push(`import ${identifier} from '${clientRoot}${name}.json';`);
    clientChunks.push(`...${identifier}`);
  }
  imports.push(`const ${track} = [${chunks.join(', ')}];`);
  writeFileSync(join(contentRoot, `${track}-assets.json`), `${JSON.stringify(payload.assets, null, 2)}\n`);
  trackEntries.push(`${track}: {cards: ${track}, assets: require('./${track}-assets.json')}`);
  clientImports.push(`import ${track}Assets from '${clientRoot}${track}-assets.json';`);
  clientTracks.push(`${track}: {cards: [${clientChunks.join(', ')}] as LearningCardRecord[], assets: ${track}Assets as BundledAudioAsset[]}`);
  for (const asset of payload.assets) {
    const destination = join(assetRoot, asset.asset_path.replace(/^audio\//, ''));
    mkdirSync(dirname(destination), {recursive: true});
    copyFileSync(resolve(dirname(path), asset.asset_path), destination);
  }
}
writeFileSync(join(contentRoot, 'index.js'), `// Generated from card-make; see provenance.json.\n${imports.join('\n')}\nmodule.exports = {${trackEntries.join(', ')}};\n`);
writeFileSync(join(contentRoot, 'provenance.json'), `${JSON.stringify(metadata, null, 2)}\n`);
writeFileSync(join(root, 'apps/mobile/src/learning/bundledCardData.ts'), `// Generated by scripts/install_bundled_card_library.mjs.\n${clientImports.join('\n')}\nimport type {LearningCardRecord} from './sourceContract';\nimport type {LearningTrack} from './model';\nimport type {BundledAudioAsset} from './bundledCardLibrary';\nexport const bundledCardData: Record<LearningTrack, {cards: LearningCardRecord[]; assets: BundledAudioAsset[]}> = {\n${clientTracks.join(',\n')}\n};\n`);
console.log(JSON.stringify(metadata, null, 2));
